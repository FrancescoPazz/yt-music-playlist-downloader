def resolve_language(choice: str) -> str:
    """"auto" means Italian on an Italian system, English everywhere else."""
    if choice in STRINGS:
        return choice
    name = (locale.getlocale()[0] or "").lower()
    return "it" if name.startswith(("it", "italian")) else "en"
